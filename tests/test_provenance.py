def test_reproducibility_bundle_manifest_matches_files():
    from ali import provenance
    from ali import sessions as store

    with tempfile.TemporaryDirectory() as tmp:
        tmp_p = Path(tmp)
        (tmp_p / "sessions").mkdir()
        with mock.patch.object(provenance, "PROV_DIR", tmp_p / "prov"), \
                mock.patch.object(store, "SESSIONS_DIR", tmp_p / "sessions"), \
                mock.patch.object(store, "ensure_state_dirs", lambda: None):
            session = store.create_session(title="Bundle test")
            rec = provenance.build_record(
                session_id=session.id,
                message_id="m1",
                user_message="q",
                final_text="a",
                route_info=_route(),
            )
            provenance.save_record(rec)
            data, name = provenance.export_session_bundle(rec["session_id"])
    assert name.endswith(".zip")
    zf = zipfile.ZipFile(io.BytesIO(data))
    names = set(zf.namelist())
    assert {"session.json", "REPORT.md", "MANIFEST.json", "provenance/m1.json"} <= names
    manifest = json.loads(zf.read("MANIFEST.json"))
    for fname, digest in manifest["files"].items():
        assert hashlib.sha256(zf.read(fname)).hexdigest() == digest
    assert manifest["records"][0]["verified"] is True
    assert "sk-THISSHOULDNEVERAPPEAR" not in zf.read("provenance/m1.json").decode()


E2E_SCRIPT = r"""
import json, sys, time
sys.path.insert(0, sys.argv[1])
from ali import sessions as store, streaming, provenance, websearch

SEARCH = json.loads(sys.argv[2])
websearch.search_structured = lambda *a, **k: SEARCH
s = store.create_session(title="e2e")
sid = s.id
res = streaming.start_chat(sid, "请检索 CRISPR 脱靶效应的最新文献并总结", web_search=True)
deadline = time.time() + 60
while time.time() < deadline:
    msgs = store.get_session(sid).messages
    if any(m.get("role") == "assistant" for m in msgs):
        break
    time.sleep(0.2)
msg = [m for m in store.get_session(sid).messages if m.get("role") == "assistant"][-1]
rec = provenance.load_record(sid, msg["id"])
print(json.dumps({
    "summary": msg.get("provenance"),
    "verified": provenance.verify_record(rec) if rec else False,
    "sources": [s["url"] for s in ((rec or {}).get("search") or {}).get("sources") or []],
    "stream_id": res["stream_id"],
    "record_stream": (rec or {}).get("stream_id"),
    "prompt_has_search": SEARCH["context_markdown"] in (((rec or {}).get("context") or {}).get("system_prompt") or {}).get("text", ""),
}))
"""


def test_start_chat_records_verified_provenance_end_to_end():
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ)
        env.update(
            {
                "HERMES_ALI_STATE_DIR": str(Path(tmp) / "state"),
                "AGENT_CLI_HOME": str(Path(tmp) / "agent-cli"),
                "HERMES_HOME": str(Path(tmp) / "hermes"),
                "HOME": tmp,
                "HERMES_ALI_AGENT_DIR": str(Path(tmp) / "no-agent"),
            }
        )
        proc = subprocess.run(
            [sys.executable, "-c", E2E_SCRIPT, str(ROOT), json.dumps(SEARCH)],
            env=env,
            capture_output=True,
            text=True,
            timeout=120,
        )
    assert proc.returncode == 0, proc.stderr[-2000:]
    out = json.loads(proc.stdout.strip().splitlines()[-1])
    assert out["summary"] and out["summary"]["schema"] == "agent-hub.provenance/1"
    assert out["verified"] is True
    assert out["sources"] == [s["url"] for s in SEARCH["sources"]]
    assert out["record_stream"] == out["stream_id"]
    assert out["prompt_has_search"] is True
