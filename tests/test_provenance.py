"""Tests for per-reply provenance records (auditable history).

Covers:
  * build_record: fields, secret redaction, base_url reduced to host,
    numbered sources, deterministic zh/en description.
  * Integrity: record_sha256 recomputes; any edit fails verification.
  * Storage round-trip, list_records ordering, Markdown report content.
  * Reproducibility bundle: zip contents and manifest hashes.
  * End-to-end (subprocess, isolated state dirs): start_chat with web search
    stores a verified provenance record whose sources match the search and
    whose system-prompt hash covers the injected search context.
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


SEARCH = {
    "ok": True,
    "query": "CRISPR off-target",
    "engines": ["pubmed", "openalex"],
    "quality": {"relevance": 0.6, "source_count": 2, "authoritative_count": 1, "verified": True},
    "warnings": [],
    "sources": [
        {"title": "Off-target effects", "url": "https://pubmed.ncbi.nlm.nih.gov/123/", "snippet": "x" * 900, "source": "pubmed"},
        {"title": "Guide design", "url": "https://openalex.org/W1", "snippet": "y", "source": "openalex"},
    ],
    "context_markdown": "## Deep information search results\n- [Off-target effects](https://pubmed.ncbi.nlm.nih.gov/123/)",
}


def _route(**extra):
    from ali import provenance

    ri = {
        "provider": "deepseek",
        "model": "deepseek-chat",
        "base_url": "https://api.deepseek.com/v1?api_key=abc",
        "api_key": "sk-THISSHOULDNEVERAPPEAR0000",
        "tier": "C2",
        "route_key": "office",
        "thinking_depth": "medium",
        "max_tokens": 4096,
        "chat_engine": "direct",
        "skills": ["literature-review"],
        "skills_source": "auto",
        "grounding": {"workspace": "/data/lab", "entry_count": 42, "excerpts": 2},
        "execution_mode": "workflow",
        "_workflow_id": "research_review",
        "_search": provenance.compact_search(SEARCH),
    }
    ri.update(extra)
    return ri


def _record(**extra):
    from ali import provenance

    return provenance.build_record(
        session_id="s1",
        message_id="m1",
        stream_id="st1",
        user_message="Summarise CRISPR off-target literature",
        preamble="system prompt with key sk-ABCDEFGHIJKLMNOPQRSTUV inside",
        final_text="Answer [1]",
        route_info=_route(),
        tools=[{"name": "web_search", "preview": "query=crispr"}],
        grounding_check={"ok": True, "soft": True},
        elapsed_ms=12300,
        started_at=1_700_000_000.0,
        **extra,
    )


def test_build_record_fields_and_redaction():
    from ali import provenance

    rec = _record()
    assert rec["schema"] == provenance.SCHEMA
    assert rec["model"]["provider"] == "deepseek"
    assert rec["model"]["base_url_host"] == "api.deepseek.com"
    assert rec["model"]["max_tokens"] == 4096
    assert rec["request"]["workflow_id"] == "research_review"
    assert rec["request"]["sha256"] == hashlib.sha256("Summarise CRISPR off-target literature".encode()).hexdigest()
    blob = json.dumps(rec)
    assert "THISSHOULDNEVERAPPEAR" not in blob
    assert "ABCDEFGHIJKLMNOPQRSTUV" not in blob
    sp = rec["context"]["system_prompt"]
    assert sp["masked_secrets"] == 1
    # hash covers what was actually sent, not the masked copy
    assert sp["sha256"] == provenance.sha256_text("system prompt with key sk-ABCDEFGHIJKLMNOPQRSTUV inside")
    assert rec["environment"]["app_version"]
    assert rec["timing"]["elapsed_ms"] == 12300


def test_sources_numbered_in_prompt_order_and_snippets_truncated():
    rec = _record()
    srcs = rec["search"]["sources"]
    assert [s["n"] for s in srcs] == [1, 2]
    assert srcs[0]["domain"] == "pubmed.ncbi.nlm.nih.gov"
    assert srcs[0]["engine"] == "pubmed"
    assert len(srcs[0]["snippet"]) <= 280


def test_description_is_deterministic_plain_language():
    rec = _record()
    zh, en = rec["description"]["zh"], rec["description"]["en"]
    assert "deepseek/deepseek-chat" in zh and "C2·office" in zh and "12.3s" in zh
    assert "检索 2 条来源" in zh and "调用工具 1 次" in zh and "literature-review" in zh
    assert en.startswith("Generated by deepseek/deepseek-chat")
    assert _record()["description"] == rec["description"]


def test_integrity_hash_detects_tampering():
    from ali import provenance

    rec = _record()
    assert provenance.verify_record(rec)
    rec["model"]["model"] = "gpt-4o"
    assert not provenance.verify_record(rec)
    assert not provenance.verify_record({"schema": provenance.SCHEMA})


def test_save_load_list_and_summary():
    from ali import provenance

    with tempfile.TemporaryDirectory() as tmp, mock.patch.object(provenance, "PROV_DIR", Path(tmp)):
        rec = _record()
        path = provenance.save_record(rec)
        assert path.is_file() and path.parent.name == "s1"
        loaded = provenance.load_record("s1", "m1")
        assert loaded == json.loads(json.dumps(rec))
        assert provenance.verify_record(loaded)
        assert provenance.load_record("s1", "../../etc") is None
        assert [r["message_id"] for r in provenance.list_records("s1")] == ["m1"]
        summ = provenance.summary(loaded)
        assert summ["sources"] == 2 and summ["tools"] == 1
        assert summ["record_sha256"] == loaded["integrity"]["record_sha256"]


